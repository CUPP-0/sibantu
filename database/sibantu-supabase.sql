CREATE OR REPLACE FUNCTION sibantu_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  CREATE TRIGGER trg_regions_updated_at BEFORE UPDATE ON regions
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
  CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
  CREATE TRIGGER trg_beneficiaries_updated_at BEFORE UPDATE ON beneficiaries
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
  CREATE TRIGGER trg_programs_updated_at BEFORE UPDATE ON assistance_programs
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
  CREATE TRIGGER trg_distribution_events_updated_at BEFORE UPDATE ON distribution_events
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
  CREATE TRIGGER trg_claims_updated_at BEFORE UPDATE ON beneficiary_claims
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$
BEGIN
  CREATE TRIGGER trg_complaints_updated_at BEFORE UPDATE ON complaints
    FOR EACH ROW EXECUTE FUNCTION sibantu_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

