CREATE TABLE IF NOT EXISTS regions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT REFERENCES regions(id) ON DELETE RESTRICT,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  level VARCHAR(16) NOT NULL CHECK (level IN ('provinsi', 'kabupaten', 'kecamatan', 'desa')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_regions_parent_level ON regions(parent_id, level);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('super_admin', 'admin_daerah', 'petugas', 'masyarakat')),
  wilayah_id BIGINT REFERENCES regions(id) ON DELETE RESTRICT,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_users_role_region ON users(role, wilayah_id);

CREATE TABLE IF NOT EXISTS beneficiaries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nik_encrypted TEXT NOT NULL,
  nik_lookup_hash CHAR(64) NOT NULL UNIQUE,
  no_kk_encrypted TEXT,
  name VARCHAR(150) NOT NULL,
  gender CHAR(1) NOT NULL CHECK (gender IN ('L', 'P')),
  birth_date DATE NOT NULL,
  address TEXT NOT NULL,
  phone_encrypted TEXT,
  region_id BIGINT NOT NULL REFERENCES regions(id) ON DELETE RESTRICT,
  verification_status VARCHAR(24) NOT NULL DEFAULT 'menunggu'
    CHECK (verification_status IN ('menunggu', 'terverifikasi', 'ditolak', 'perlu_pembaruan')),
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_beneficiaries_region_status ON beneficiaries(region_id, verification_status);
CREATE INDEX IF NOT EXISTS idx_beneficiaries_name ON beneficiaries(name);

CREATE TABLE IF NOT EXISTS citizen_accounts (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE RESTRICT,
  beneficiary_id BIGINT NOT NULL UNIQUE REFERENCES beneficiaries(id) ON DELETE RESTRICT,
  verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assistance_programs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  description TEXT NOT NULL,
  category VARCHAR(80) NOT NULL,
  assistance_type VARCHAR(16) NOT NULL CHECK (assistance_type IN ('tunai', 'non_tunai', 'barang', 'layanan')),
  amount NUMERIC(15, 2),
  quota INTEGER NOT NULL DEFAULT 0 CHECK (quota >= 0),
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'aktif', 'selesai', 'arsip')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_program_status_period ON assistance_programs(status, start_date, end_date);

CREATE TABLE IF NOT EXISTS beneficiary_programs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beneficiary_id BIGINT NOT NULL REFERENCES beneficiaries(id) ON DELETE RESTRICT,
  program_id BIGINT NOT NULL REFERENCES assistance_programs(id) ON DELETE RESTRICT,
  assistance_amount NUMERIC(15, 2),
  registration_date DATE NOT NULL,
  eligibility_status VARCHAR(16) NOT NULL DEFAULT 'menunggu'
    CHECK (eligibility_status IN ('menunggu', 'layak', 'tidak_layak')),
  verification_status VARCHAR(20) NOT NULL DEFAULT 'menunggu'
    CHECK (verification_status IN ('menunggu', 'terverifikasi', 'ditolak')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_beneficiary_program UNIQUE (beneficiary_id, program_id)
);
CREATE INDEX IF NOT EXISTS idx_beneficiary_program_status ON beneficiary_programs(program_id, verification_status);

CREATE TABLE IF NOT EXISTS distribution_schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_id BIGINT NOT NULL REFERENCES assistance_programs(id) ON DELETE RESTRICT,
  region_id BIGINT NOT NULL REFERENCES regions(id) ON DELETE RESTRICT,
  officer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  scheduled_date TIMESTAMPTZ NOT NULL,
  location VARCHAR(255) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'dijadwalkan'
    CHECK (status IN ('dijadwalkan', 'berlangsung', 'selesai', 'ditunda', 'dibatalkan')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_schedule_region_date ON distribution_schedules(region_id, scheduled_date);

CREATE TABLE IF NOT EXISTS distribution_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  region_id BIGINT NOT NULL REFERENCES regions(id) ON DELETE RESTRICT,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  title VARCHAR(160) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  scheduled_at TIMESTAMPTZ NOT NULL,
  location VARCHAR(255) NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_distribution_events_region_date
  ON distribution_events(region_id, is_active, scheduled_at);

CREATE TABLE IF NOT EXISTS distributions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beneficiary_program_id BIGINT NOT NULL UNIQUE REFERENCES beneficiary_programs(id) ON DELETE RESTRICT,
  officer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  schedule_id BIGINT REFERENCES distribution_schedules(id) ON DELETE SET NULL,
  amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
  distribution_date TIMESTAMPTZ NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'menunggu'
    CHECK (status IN ('dijadwalkan', 'menunggu', 'berhasil', 'gagal', 'ditunda')),
  reference_number VARCHAR(80) NOT NULL UNIQUE,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_distributions_status_date ON distributions(status, distribution_date);

CREATE TABLE IF NOT EXISTS qr_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beneficiary_program_id BIGINT NOT NULL REFERENCES beneficiary_programs(id) ON DELETE RESTRICT,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_qr_program_active ON qr_tokens(beneficiary_program_id, is_active);

CREATE TABLE IF NOT EXISTS complaints (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_number VARCHAR(24) NOT NULL UNIQUE,
  reporter_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  category VARCHAR(80) NOT NULL,
  region_id BIGINT NOT NULL REFERENCES regions(id) ON DELETE RESTRICT,
  description TEXT NOT NULL,
  attachment_path VARCHAR(500),
  status VARCHAR(24) NOT NULL DEFAULT 'diterima'
    CHECK (status IN ('diterima', 'ditinjau', 'investigasi', 'menunggu_informasi', 'selesai', 'ditolak')),
  assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_complaints_region_status ON complaints(region_id, status, created_at);

CREATE TABLE IF NOT EXISTS complaint_histories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id BIGINT NOT NULL REFERENCES complaints(id) ON DELETE RESTRICT,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  old_status VARCHAR(40),
  new_status VARCHAR(40) NOT NULL,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_complaint_history ON complaint_histories(complaint_id, created_at);

CREATE TABLE IF NOT EXISTS complaint_private_data (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id BIGINT NOT NULL UNIQUE REFERENCES complaints(id) ON DELETE RESTRICT,
  reporter_name_encrypted TEXT NOT NULL,
  contact_encrypted TEXT NOT NULL,
  contact_lookup_hash CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_private_contact_hash ON complaint_private_data(contact_lookup_hash);

CREATE TABLE IF NOT EXISTS otp_verifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_identifier_hash CHAR(64) NOT NULL,
  otp_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  verified_at TIMESTAMPTZ,
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_otp_lookup ON otp_verifications(user_identifier_hash, expires_at);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(80) NOT NULL,
  entity_type VARCHAR(80),
  entity_id BIGINT,
  metadata JSONB,
  ip_address VARCHAR(45),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_user_time ON audit_logs(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_logs(entity_type, entity_id, created_at);

CREATE TABLE IF NOT EXISTS beneficiary_claims (
  beneficiary_program_id BIGINT PRIMARY KEY REFERENCES beneficiary_programs(id) ON DELETE RESTRICT,
  status VARCHAR(16) NOT NULL DEFAULT 'belum_diambil' CHECK (status IN ('belum_diambil', 'sudah_diambil')),
  cycle_number INTEGER NOT NULL DEFAULT 1 CHECK (cycle_number > 0),
  claimed_at TIMESTAMPTZ,
  claimed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_beneficiary_claim_status ON beneficiary_claims(status, updated_at);

CREATE TABLE IF NOT EXISTS beneficiary_claim_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beneficiary_program_id BIGINT NOT NULL REFERENCES beneficiary_programs(id) ON DELETE RESTRICT,
  cycle_number INTEGER NOT NULL CHECK (cycle_number > 0),
  action VARCHAR(8) NOT NULL CHECK (action IN ('diambil', 'reset')),
  officer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  reference_number VARCHAR(80),
  amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_claim_history_program_cycle ON beneficiary_claim_history(beneficiary_program_id, cycle_number, occurred_at);
CREATE INDEX IF NOT EXISTS idx_claim_history_date ON beneficiary_claim_history(occurred_at);

