CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;

DO $$
DECLARE
  existing_job BIGINT;
BEGIN
  FOR existing_job IN
    SELECT jobid FROM cron.job WHERE jobname = 'sibantu-delete-expired-distribution-events'
  LOOP
    PERFORM cron.unschedule(existing_job);
  END LOOP;

  PERFORM cron.schedule(
    'sibantu-delete-expired-distribution-events',
    '* * * * *',
    'DELETE FROM public.distribution_events WHERE scheduled_at <= now()'
  );
END $$;
